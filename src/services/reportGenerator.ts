import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { ATSScoreBreakdown, CandidateProfile, JobDescription } from '../types';

/**
 * Generates and downloads a Candidate ATS Screening & Explainability PDF Report
 */
export function generateCandidateReportPDF(
  candidate: CandidateProfile,
  job: JobDescription,
  breakdown: ATSScoreBreakdown
): void {
  const doc = new jsPDF();

  // Header Banner
  doc.setFillColor(30, 41, 59); // Slate dark navy
  doc.rect(0, 0, 210, 35, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('EXPLAINABLE ATS RESUME SCREENING REPORT', 14, 18);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text('Academic Research Prototype | Rule-Based Natural Language Processing', 14, 26);

  // Candidate & Job Context Box
  doc.setTextColor(30, 41, 59);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.text(`Candidate: ${candidate.fullName}`, 14, 45);
  doc.text(`Target Job: ${job.title} (${job.companyName})`, 14, 52);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text(`Email: ${candidate.email} | Phone: ${candidate.phone}`, 14, 58);
  doc.text(`Date of Evaluation: ${new Date().toLocaleDateString()}`, 14, 64);

  // Score Summary Table
  autoTable(doc, {
    startY: 70,
    head: [['Scoring Component', 'Raw Metric', 'Weight %', 'Points Earned']],
    body: [
      ['Skill Alignment', `${breakdown.skillScoreRaw}%`, '40%', `${breakdown.skillScoreWeighted} / 40.0`],
      ['Project Quality', `${breakdown.projectScoreRaw}%`, '20%', `${breakdown.projectScoreWeighted} / 20.0`],
      ['Work Experience', `${breakdown.expScoreRaw}%`, '20%', `${breakdown.expScoreWeighted} / 20.0`],
      ['Education Level', `${breakdown.eduScoreRaw}%`, '10%', `${breakdown.eduScoreWeighted} / 10.0`],
      ['Certifications', `${breakdown.certScoreRaw}%`, '10%', `${breakdown.certScoreWeighted} / 10.0`],
      ['OVERALL ATS MATCH SCORE', '-', '100%', `${breakdown.overallScore}% (${breakdown.classification})`]
    ],
    theme: 'grid',
    headStyles: { fillColor: [51, 65, 85], textColor: 255, fontStyle: 'bold' },
    bodyStyles: { fontSize: 9 }
  });

  let currentY = (doc as any).lastAutoTable.finalY + 10;

  // Skills Summary Table
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('SKILL GAP & MATCH ANALYSIS', 14, currentY);

  const skillRows: string[][] = [];

  // Exact Matches
  breakdown.exactMatchedSkills.forEach((s) => {
    skillRows.push(['Exact Match', s, '100% Full Credit', 'Direct keyword detection']);
  });

  // Related Matches
  breakdown.relatedMatchedSkills.forEach((r) => {
    skillRows.push([
      'Related Match',
      `${r.requiredSkill} (via ${r.candidateSkill})`,
      `${r.creditEarnedPercentage}% Partial Credit`,
      `${r.relationshipType}: ${r.explanation}`
    ]);
  });

  // Missing Skills
  breakdown.missingSkills.forEach((m) => {
    skillRows.push(['Missing Skill', m, '0% Credit', 'Action Required: Learn or highlight this skill']);
  });

  autoTable(doc, {
    startY: currentY + 4,
    head: [['Match Category', 'Skill Name', 'Credit Awarded', 'Explainability Justification']],
    body: skillRows.length > 0 ? skillRows : [['-', 'No skills recorded', '0%', '-']],
    theme: 'striped',
    headStyles: { fillColor: [71, 85, 105], textColor: 255 },
    bodyStyles: { fontSize: 8.5 }
  });

  currentY = (doc as any).lastAutoTable.finalY + 10;

  // Recommendations & Audit Log
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('RECOMMENDED ACTIONABLE IMPROVEMENTS', 14, currentY);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  currentY += 6;

  breakdown.improvementSuggestions.forEach((sug, i) => {
    doc.text(`${i + 1}. ${sug}`, 16, currentY);
    currentY += 6;
  });

  // Footer / Research Disclaimer
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text('Generated by Explainable Skill-Based ATS Screening System | Rule-Based Natural Language Processing | No Black-Box AI Models Used', 14, 285);

  doc.save(`ATS_Report_${candidate.fullName.replace(/\s+/g, '_')}_${job.title.replace(/\s+/g, '_')}.pdf`);
}

/**
 * Generates and downloads Recruiter Comparative Screening Matrix PDF Report
 */
export function generateRecruiterRankingReportPDF(
  job: JobDescription,
  rankedCandidates: { candidate: CandidateProfile; breakdown: ATSScoreBreakdown; rank: number }[]
): void {
  const doc = new jsPDF('landscape');

  // Header Banner
  doc.setFillColor(30, 41, 59);
  doc.rect(0, 0, 297, 30, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text(`RECRUITER CANDIDATE RANKING MATRIX - ${job.title.toUpperCase()}`, 14, 16);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(`Company: ${job.companyName} | Total Candidates Screened: ${rankedCandidates.length} | Generated: ${new Date().toLocaleDateString()}`, 14, 24);

  const tableData = rankedCandidates.map((item) => [
    `#${item.rank}`,
    item.candidate.fullName,
    `${item.breakdown.overallScore}%`,
    item.breakdown.classification,
    `${item.breakdown.skillScoreWeighted}/40 (${item.breakdown.skillScoreRaw}%)`,
    `${item.breakdown.projectScoreWeighted}/20`,
    `${item.breakdown.expScoreWeighted}/20 (${item.candidate.totalExpYears} yrs)`,
    `${item.breakdown.eduScoreWeighted}/10`,
    item.breakdown.exactMatchedSkills.join(', ') || 'None',
    item.breakdown.missingSkills.join(', ') || 'None'
  ]);

  autoTable(doc, {
    startY: 38,
    head: [['Rank', 'Candidate Name', 'Overall', 'Classification', 'Skills', 'Projects', 'Exp', 'Edu', 'Matched Skills', 'Missing Skills']],
    body: tableData,
    theme: 'grid',
    headStyles: { fillColor: [30, 41, 59], textColor: 255, fontStyle: 'bold' },
    bodyStyles: { fontSize: 8.5 },
    columnStyles: {
      0: { cellWidth: 15 },
      1: { cellWidth: 40 },
      2: { cellWidth: 20 },
      3: { cellWidth: 30 },
      4: { cellWidth: 25 },
      5: { cellWidth: 20 },
      6: { cellWidth: 25 },
      7: { cellWidth: 15 },
      8: { cellWidth: 45 },
      9: { cellWidth: 40 }
    }
  });

  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text('Note: Ranking is generated using transparent rule-based scoring and relationship mapping without demographic bias.', 14, 198);

  doc.save(`Recruiter_Ranking_Matrix_${job.title.replace(/\s+/g, '_')}.pdf`);
}
